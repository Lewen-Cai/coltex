// The symbol palette's symbols: the LaTeX command to insert, a Unicode preview,
// and the package that defines it when it isn't in the LaTeX kernel. Grouped
// like Overleaf's palette (Greek, arrows, operators, relations, miscellaneous).
// ColTex's own list: Overleaf's palette data isn't part of Overleaf CE.

export type SymbolCategory = 'greek' | 'arrows' | 'operators' | 'relations' | 'misc'

export type LatexSymbol = {
  command: string
  /** What it looks like (Unicode), shown in the palette. */
  preview: string
  category: SymbolCategory
  /** The package that defines it, if any. */
  pkg?: 'amssymb' | 'amsmath' | 'mathtools'
  /** Extra search words (English), besides the command name. */
  keywords?: string
}

type Row = [command: string, preview: string, pkg?: LatexSymbol['pkg'], keywords?: string]

const rows = (category: SymbolCategory, list: Row[]): LatexSymbol[] =>
  list.map(([command, preview, pkg, keywords]) => ({ command, preview, category, pkg, keywords }))

