// Build the Lezer parsers from the ported grammars (mirrors Overleaf's
// services/web/scripts/lezer-latex/generate.mjs). Output is committed.
import { buildParserFile } from '@lezer/generator'
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

for (const name of ['latex', 'bibtex']) {
  const dir = path.resolve(import.meta.dirname, `src/lezer-${name}`)
  const grammarPath = path.join(dir, `${name}.grammar`)
  const { parser, terms } = buildParserFile(readFileSync(grammarPath, 'utf8'), {
    fileName: grammarPath,
    moduleStyle: 'es',
  })
  const banner = `// Generated by scripts-generate.mjs from ${name}.grammar (ported from Overleaf, AGPL-3.0). Do not edit.\n`
  writeFileSync(path.join(dir, `${name}.mjs`), banner + parser)
  writeFileSync(path.join(dir, `${name}.terms.mjs`), banner + terms)
  console.log(`generated lezer-${name}`)
}
